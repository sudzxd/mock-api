def test_server_initialization(models_file: str) -> None:
    """Test Server initializes correctly."""
    server = Server(models_file)

    assert server.models_file == models_file
    assert server.prefix == "/api/v1"
    assert server.generate_data is False
    assert server.data_count == 10
    assert server.parser is not None
    assert len(server.schemas) > 0
    assert server.store is not None
    assert server.router_generator is not None


