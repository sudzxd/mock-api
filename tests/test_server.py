def test_create_app_returns_fastapi(server: Server) -> None:
    """Test create_app returns FastAPI instance."""
    app = server.create_app()

    assert isinstance(app, FastAPI)
    assert app.title == "Mock API"
    assert app.version == "1.0.0"


def test_create_app_includes_routes(server: Server) -> None:
    """Test create_app includes all generated routes."""
    app = server.create_app()

    # Each model gets 5 routes
    total_models = len(server.schemas)
    expected_routes = total_models * 5

    # Count only API CRUD routes (exclude docs, openapi, etc)
    api_routes = [
        r
        for r in app.routes
        if hasattr(r, "path") and r.path.startswith(server.prefix)  # type: ignore[attr-defined]
    ]
    assert len(api_routes) == expected_routes


def test_create_app_docs_enabled(server: Server) -> None:
    """Test create_app enables OpenAPI docs."""
    app = server.create_app()

    assert app.docs_url == "/docs"
    assert app.redoc_url == "/redoc"


def test_app_property_lazy_initialization(server: Server) -> None:
    """Test app property creates app on first access."""
    # App not created yet
    assert not server.has_app

    # Access app property
    app = server.app

    # App created and cached
    assert isinstance(app, FastAPI)
    assert server.has_app

    # Second access returns same instance
    app2 = server.app
    assert app2 is app


