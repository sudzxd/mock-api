def test_server_crud_read(client: TestClient, server: Server) -> None:
    """Test read operation via server."""
    # Create data
    created = server.store.create(
        "Contact",
        {
            "name": "Alice",
            "email": "alice@example.com",
            "phone": "555-1234",
            "username": "alice",
            "first_name": "Alice",
            "last_name": "Smith",
        },
    )

    # Read via API
    response = client.get(f"/api/v1/contacts/{created['id']}")

    assert response.status_code == HTTPStatus.OK
    data = response.json()
    assert data["id"] == created["id"]
    assert data["name"] == "Alice"


