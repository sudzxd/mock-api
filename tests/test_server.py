def test_server_crud_list(client: TestClient, server: Server) -> None:
    """Test list operation via server."""
    # Create multiple items
    for i in range(5):
        server.store.create(
            "Contact",
            {
                "name": f"User {i}",
                "email": f"user{i}@example.com",
                "phone": f"555-{i:04d}",
                "username": f"user{i}",
                "first_name": "User",
                "last_name": f"{i}",
            },
        )

    # List via API
    response = client.get("/api/v1/contacts")

    assert response.status_code == HTTPStatus.OK
    data = response.json()
    assert len(data["items"]) == 5
    assert data["pagination"]["total_items"] == 5


